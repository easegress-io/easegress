package tcpproxy

import (
	"fmt"
	stdnet "net"
	"reflect"
	"sync/atomic"
	"time"

	"github.com/megaease/easegress/v2/pkg/graceupdate"
	"github.com/megaease/easegress/v2/pkg/logger"
	"github.com/megaease/easegress/v2/pkg/supervisor"
	"github.com/megaease/easegress/v2/pkg/util/limitlistener"
)

const (
	stateNil     stateType = "nil"
	stateFailed  stateType = "failed"
	stateRunning stateType = "running"
	stateClosed  stateType = "closed"

	checkFailedTimeout = 10 * time.Second
)

var (
	errNil = fmt.Errorf("")
	gnet   = graceupdate.Global
)

type (
	stateType string

	eventCheckFailed struct{}
	eventServeFailed struct {
		roundNum uint64
		err      error
	}
	eventReload struct {
		nextSuperSpec *supervisor.Spec
	}
	eventClose struct{ done chan struct{} }

	runtime struct {
		superSpec *supervisor.Spec
		spec      *Spec

		listener      stdnet.Listener
		limitListener *limitlistener.LimitListener
		loadBalancer  LoadBalancer

		roundNum  uint64
		eventChan chan interface{}

		// status
		state atomic.Value // stateType
		err   atomic.Value // error

		// connection count
		connections int64
	}

	// Status contains all status generated by runtime, for displaying to users.
	Status struct {
		Health      bool      `json:"health"`
		State       stateType `json:"state"`
		Error       string    `json:"error,omitempty"`
		Connections int64     `json:"connections"`
	}
)

func newRuntime(superSpec *supervisor.Spec) *runtime {
	r := &runtime{
		superSpec: superSpec,
		eventChan: make(chan interface{}, 10),
	}
	r.setState(stateNil)
	r.setError(errNil)

	go r.fsm()
	go r.checkFailed(checkFailedTimeout)

	return r
}

// Close closes runtime.
func (r *runtime) Close() {
	done := make(chan struct{})
	r.eventChan <- &eventClose{done: done}
	<-done
}

// Status returns TCPProxy Status.
func (r *runtime) Status() *Status {
	err := r.getError()
	return &Status{
		Health:      err.Error() == errNil.Error(),
		State:       r.getState(),
		Error:       err.Error(),
		Connections: atomic.LoadInt64(&r.connections),
	}
}

// FSM is the finite-state-machine for the runtime.
func (r *runtime) fsm() {
	for e := range r.eventChan {
		switch e := e.(type) {
		case *eventCheckFailed:
			r.handleEventCheckFailed(e)
		case *eventServeFailed:
			r.handleEventServeFailed(e)
		case *eventReload:
			r.handleEventReload(e)
		case *eventClose:
			r.handleEventClose(e)
			return
		default:
			logger.Errorf("BUG: unknown event: %T\n", e)
		}
	}
}

func (r *runtime) reload(nextSuperSpec *supervisor.Spec) {
	r.superSpec = nextSuperSpec
	nextSpec := nextSuperSpec.ObjectSpec().(*Spec)

	// r.limitListener is not created just after the process started and the config load for the first time.
	if nextSpec != nil && r.limitListener != nil {
		r.limitListener.SetMaxConnection(nextSpec.MaxConnections)
	}

	// NOTE: Due to the mechanism of supervisor,
	// nextSpec must not be nil, just defensive programming here.
	switch {
	case r.spec == nil && nextSpec == nil:
		logger.Errorf("BUG: nextSpec is nil")
		// Nothing to do.
	case r.spec == nil && nextSpec != nil:
		r.spec = nextSpec
		r.loadBalancer = NewLoadBalancer(nextSpec.LoadBalance, nextSpec.Backends)
		r.startServer()
	case r.spec != nil && nextSpec == nil:
		logger.Errorf("BUG: nextSpec is nil")
		r.spec = nil
		r.closeServer()
	case r.spec != nil && nextSpec != nil:
		if r.needRestartServer(nextSpec) {
			r.spec = nextSpec
			r.loadBalancer = NewLoadBalancer(nextSpec.LoadBalance, nextSpec.Backends)
			r.closeServer()
			r.startServer()
		} else {
			r.spec = nextSpec
			// Update load balancer even if we don't restart.
			r.loadBalancer = NewLoadBalancer(nextSpec.LoadBalance, nextSpec.Backends)
		}
	}
}

func (r *runtime) setState(state stateType) {
	r.state.Store(state)
}

func (r *runtime) getState() stateType {
	return r.state.Load().(stateType)
}

func (r *runtime) setError(err error) {
	if err == nil {
		r.err.Store(errNil)
	} else {
		r.err.Store(fmt.Errorf("%v", err))
	}
}

func (r *runtime) getError() error {
	err := r.err.Load()
	if err == nil {
		return nil
	}
	return err.(error)
}

func (r *runtime) needRestartServer(nextSpec *Spec) bool {
	x := *r.spec
	y := *nextSpec

	// The change of options below need not restart the server.
	x.MaxConnections, y.MaxConnections = 0, 0
	x.Backends, y.Backends = nil, nil
	x.LoadBalance, y.LoadBalance = "", ""

	return !reflect.DeepEqual(x, y)
}

func (r *runtime) startServer() {
	atomic.AddUint64(&r.roundNum, 1)
	r.setState(stateRunning)
	r.setError(errNil)

	addr := fmt.Sprintf("%s:%d", r.spec.Address, r.spec.Port)
	listener, err := gnet.Listen("tcp", addr)
	if err != nil {
		logger.Errorf("tcpproxy %s failed to listen on %s: %v",
			r.superSpec.Name(), addr, err)
		r.setState(stateFailed)
		r.setError(err)
		return
	}

	r.listener = listener
	limitListener := limitlistener.NewLimitListener(listener, r.spec.MaxConnections)
	r.limitListener = limitListener

	go r.serve(limitListener)
}

func (r *runtime) serve(listener stdnet.Listener) {
	for {
		clientConn, err := listener.Accept()
		if err != nil {
			// Listener closed or failed.
			if r.getState() == stateRunning {
				logger.Errorf("tcpproxy %s accept failed: %v",
					r.superSpec.Name(), err)
				r.eventChan <- &eventServeFailed{
					err: err,
				}
			}
			return
		}

		atomic.AddInt64(&r.connections, 1)
		go r.handleConnection(clientConn)
	}
}

func (r *runtime) handleConnection(clientConn stdnet.Conn) {
	defer func() {
		atomic.AddInt64(&r.connections, -1)
		clientConn.Close()
	}()

	// Select backend.
	backendAddr := r.loadBalancer.Next()
	if backendAddr == "" {
		logger.Warnf("tcpproxy %s: no backend available", r.superSpec.Name())
		return
	}

	// Parse timeouts.
	var connectTimeout time.Duration
	if r.spec.ConnectTimeout != "" {
		connectTimeout, _ = time.ParseDuration(r.spec.ConnectTimeout)
	} else {
		connectTimeout = 10 * time.Second
	}

	var idleTimeout time.Duration
	if r.spec.IdleTimeout != "" {
		idleTimeout, _ = time.ParseDuration(r.spec.IdleTimeout)
	}

	// Connect to backend.
	var backendConn stdnet.Conn
	var err error
	if connectTimeout > 0 {
		backendConn, err = stdnet.DialTimeout("tcp", backendAddr, connectTimeout)
	} else {
		backendConn, err = stdnet.Dial("tcp", backendAddr)
	}
	if err != nil {
		logger.Warnf("tcpproxy %s: connect to backend %s failed: %v",
			r.superSpec.Name(), backendAddr, err)
		return
	}
	defer backendConn.Close()

	// Handle TLS termination if configured.
	var clientSideConn stdnet.Conn = clientConn
	if r.spec.TLS != nil && r.spec.TLS.Enable {
		tlsConfig, tlsErr := r.spec.TLS.tlsConfig()
		if tlsErr != nil {
			logger.Errorf("tcpproxy %s: TLS config error: %v",
				r.superSpec.Name(), tlsErr)
			return
		}
		tlsConn := &stdTLSConn{
			Conn:   clientConn,
			config: tlsConfig,
		}
		if err := tlsConn.handshake(); err != nil {
			logger.Warnf("tcpproxy %s: TLS handshake failed: %v",
				r.superSpec.Name(), err)
			return
		}
		clientSideConn = tlsConn
	}

	// Proxy bidirectional traffic.
	proxy(clientSideConn, backendConn, idleTimeout)
}

func (r *runtime) closeServer() {
	if r.limitListener != nil {
		if err := r.limitListener.Close(); err != nil {
			logger.Warnf("tcpproxy %s: close limit listener failed: %v",
				r.superSpec.Name(), err)
		}
		r.limitListener = nil
	}
	if r.listener != nil {
		if err := r.listener.Close(); err != nil {
			logger.Warnf("tcpproxy %s: close listener failed: %v",
				r.superSpec.Name(), err)
		}
		r.listener = nil
	}
}

func (r *runtime) checkFailed(timeout time.Duration) {
	ticker := time.NewTicker(timeout)
	for range ticker.C {
		state := r.getState()
		if state == stateFailed {
			r.eventChan <- &eventCheckFailed{}
		} else if state == stateClosed {
			ticker.Stop()
			return
		}
	}
}

func (r *runtime) handleEventCheckFailed(e *eventCheckFailed) {
	if r.getState() == stateFailed {
		r.startServer()
	}
}

func (r *runtime) handleEventServeFailed(e *eventServeFailed) {
	if e.roundNum != 0 && atomic.LoadUint64(&r.roundNum) > e.roundNum {
		return
	}
	logger.Errorf("tcpproxy %v failed: %v", r.superSpec.Name(), e.err)
	r.setState(stateFailed)
	r.setError(e.err)
}

func (r *runtime) handleEventReload(e *eventReload) {
	r.reload(e.nextSuperSpec)
}

func (r *runtime) handleEventClose(e *eventClose) {
	r.setState(stateClosed)
	r.setError(errNil)
	r.closeServer()
	close(e.done)
}
